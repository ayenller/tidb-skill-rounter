#!/usr/bin/env node
// Export the commands for other agent runtimes.
//
// DESIGN.md claims the catalog, the overlay, the retriever, the verifier and
// the trajectory are agent-agnostic, and that only the command layer is
// Claude-specific. This script is that claim made testable: it regenerates the
// same commands for OpenCode and Codex from the single source in commands/,
// rewriting only the frontmatter, the argument placeholder and the root
// variable. If porting ever needs more than this file, the claim was false.
//
// Upstream nutshell-skills already installs its skills into all three runtimes
// via sync-skills.sh; adapters/install.sh does the same for ours.

import fs from 'node:fs';
import path from 'node:path';
import { parseFrontmatter } from './lib/yaml-lite.mjs';
import { PLUGIN_ROOT } from './lib/paths.mjs';

const TARGETS = {
  opencode: {
    dir: 'adapters/opencode/command',
    skillRef: '@.opencode/skills/tidb-aio-router/SKILL.md',
    frontmatter: (fm) => `---\ndescription: ${fm.description}\n---`,
    // OpenCode commands take positional args rather than one $ARGUMENTS blob.
    args: '$1',
  },
  codex: {
    dir: 'adapters/codex/prompts',
    skillRef: '~/.codex/skills/tidb-aio-router/SKILL.md',
    frontmatter: (fm) => `---\ndescription: ${fm.description}\n---`,
    args: '$ARGUMENTS',
  },
};

function body(raw) {
  const end = raw.indexOf('\n---', 4);
  return raw.slice(raw.indexOf('\n', end + 1) + 1).trimStart();
}

function main() {
  const commandsDir = path.join(PLUGIN_ROOT, 'commands');
  const files = fs.readdirSync(commandsDir).filter((f) => f.endsWith('.md')).sort();
  const written = [];

  for (const [target, spec] of Object.entries(TARGETS)) {
    const outDir = path.join(PLUGIN_ROOT, spec.dir);
    fs.mkdirSync(outDir, { recursive: true });
    for (const file of files) {
      const raw = fs.readFileSync(path.join(commandsDir, file), 'utf8');
      const fm = parseFrontmatter(raw) || {};
      let text = body(raw)
        .replaceAll('${CLAUDE_PLUGIN_ROOT}', '${TIDB_AIO_ROOT}')
        .replaceAll('$ARGUMENTS', spec.args)
        .replaceAll('`tidb-aio-router` skill', `\`tidb-aio-router\` skill (${spec.skillRef})`);
      const out = [
        spec.frontmatter(fm),
        '',
        `<!-- generated by scripts/export-adapters.mjs from commands/${file}; do not edit -->`,
        '',
        text,
      ].join('\n');
      const dest = path.join(outDir, file);
      fs.writeFileSync(dest, out.endsWith('\n') ? out : out + '\n');
      written.push(path.relative(PLUGIN_ROOT, dest));
    }
  }

  const install = `#!/usr/bin/env bash
# Install the router into OpenCode and Codex.
#
# The catalog, overlay, retriever, verifier and trajectory are shared verbatim -
# only the command files differ, and those are generated. Regenerate them with
# \`node scripts/export-adapters.mjs\` after editing anything in commands/.
set -euo pipefail

root="$(cd "$(dirname "\${BASH_SOURCE[0]}")/.." && pwd)"

link() {  # link <src> <dest>
    mkdir -p "$(dirname "$2")"
    rm -rf "$2"
    ln -s "$1" "$2"
    echo "  $2 -> $1"
}

echo "opencode:"
link "\${root}/skills/tidb-aio-router" "\${HOME}/.config/opencode/skills/tidb-aio-router"
mkdir -p "\${HOME}/.config/opencode/command"
cp "\${root}"/adapters/opencode/command/*.md "\${HOME}/.config/opencode/command/"
echo "  commands copied to ~/.config/opencode/command/"

echo "codex:"
link "\${root}/skills/tidb-aio-router" "\${HOME}/.codex/skills/tidb-aio-router"
mkdir -p "\${HOME}/.codex/prompts"
cp "\${root}"/adapters/codex/prompts/*.md "\${HOME}/.codex/prompts/"
echo "  prompts copied to ~/.codex/prompts/"

echo
echo "Add this to your shell profile so the generated commands can find the scripts:"
echo "  export TIDB_AIO_ROOT=\\"\${root}\\""
`;
  const installPath = path.join(PLUGIN_ROOT, 'adapters', 'install.sh');
  fs.mkdirSync(path.dirname(installPath), { recursive: true });
  fs.writeFileSync(installPath, install);
  fs.chmodSync(installPath, 0o755);
  written.push('adapters/install.sh');

  console.log(`exported ${files.length} command(s) for ${Object.keys(TARGETS).join(', ')}`);
  for (const w of written) console.log(`  ${w}`);
  console.log('\nShared verbatim across all three runtimes: catalog, overlay, lexicon,');
  console.log('retriever, verifier, trajectory, eval, and the router skill itself.');
}

main();
